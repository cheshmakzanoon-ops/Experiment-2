    private val categoryOrder =
        listOf(
            "Sketching",
            "Inking",
            "Drawing",
            "Painting",
            "Artistic",
            "Calligraphy",
            "Airbrushing",
            "Textures",
            "Charcoals",
            "Spraypaints",
            "Elements",
            "Touch-ups",
            "Retro",
            "Luminance",
            "Industrial",
            "Organic",
            "Water",
            "Abstract",
        )

    val categories: List<String> =
        listOf("All") + categoryOrder.filter { category -> presets.any { it.category == category } } +
            presets.map { it.category }.distinct().filterNot { it in categoryOrder }

    fun search(
        query: String,
        category: String = "All",
    ): List<Preset> {
        val words = query.trim().split(Regex("\\s+")).filter { it.isNotEmpty() }
        return presets.filter { preset ->
            val description = "${preset.name} ${preset.category} ${preset.description}"
            (category == "All" || preset.category == category) && words.all { description.contains(it, ignoreCase = true) }
        }
    }
}
