/** Historical ArtFlow v4 pixels and the separately imported source-19 native layer contract. */
@RunWith(AndroidJUnit4::class)
class ProcreateLegacyDarkenDeviceTest {
    private lateinit var context: Context
    private lateinit var directory: File
    private lateinit var storage: ProjectStorage
    private lateinit var repository: CanvasRepositoryImpl

    @Before
    fun setUp() {
        val application = ApplicationProvider.getApplicationContext<Context>()
        directory = Files.createTempDirectory(application.cacheDir.toPath(), "native-darken-").toFile()
        context =
            object : ContextWrapper(application) {
                override fun getFilesDir(): File = directory
            }
        storage = ProjectStorage(context)
        repository = CanvasRepositoryImpl(storage)
    }

    @After
    fun tearDown() =
        runBlocking(Dispatchers.Main) {
            repository.dispose()
            StorageFileTree.delete(directory)
        }

    @Test
    fun nativeDarkenSurvivesImportEditUndoAndReopenWithoutReinterpretingSignedV4() =
        runBlocking(Dispatchers.Main) {
            // Generated by the unchanged published v4 codec and independently rendered by that build.
            // Neither this historical asset nor the native rational fixtures are native-executed goldens.
            val original =
                InstrumentationRegistry
                    .getInstrumentation()
                    .context
                    .assets
                    .open("migration/standard-darken-v4.artflow")
                    .use { it.readBytes() }
            assertEquals(1990, original.size)
            assertEquals(HISTORICAL_SHA, sha256(original))
            assertSigned(original, 4)
            assertFalse(original.toString(Charsets.UTF_8).contains("blendContract"))
            evidence("native-darken-v4-before-load.artflow", original)
            assertEquals(HISTORICAL_PIXELS_SHA, pixelHash(standardPixels()))
            writeHistoricalRaster("rasters/base.png", basePixels())
            writeHistoricalRaster("rasters/darken.png", sourcePixels())
            val oldFile = storage.documentFile(HISTORICAL_PROJECT)
            val tampered =
                original
                    .toString(Charsets.UTF_8)
                    .replace("\"blendMode\":\"DARKEN\"", "\"blendMode\":\"NORMAL\"")
                    .toByteArray()
            assertNotEquals(original.toString(Charsets.UTF_8), tampered.toString(Charsets.UTF_8))
            oldFile.writeBytes(tampered)
            val error = runCatching { storage.loadDocument(HISTORICAL_PROJECT) }.exceptionOrNull()
            assertTrue("Historical edit must fail its original checksum", error is IllegalArgumentException)
            assertTrue(error?.message.orEmpty().contains("checksum"))
            assertArrayEquals(tampered, oldFile.readBytes())
            oldFile.writeBytes(original)

            requireNotNull(repository.loadCanvas(HISTORICAL_PROJECT))
            assertStack(LayerBlendContract.STANDARD, standardPixels())
            assertArrayEquals("Loading must not rewrite the signed v4 file", original, oldFile.readBytes())
            val historicalSaved = save(HISTORICAL_PROJECT, "native-darken-v5-historical-standard.artflow")
            reopen(HISTORICAL_PROJECT)
            assertStack(LayerBlendContract.STANDARD, standardPixels())
            assertArrayEquals(historicalSaved, oldFile.readBytes())

            repository.dispose()
            repository = CanvasRepositoryImpl(storage)
            repository.loadOrCreate(IMPORTED_PROJECT, WIDTH, HEIGHT, 72)
            assertEquals(0xFFFFFFFF.toInt(), repository.getBackgroundColor())
            val incoming = nativeFixture()
            evidence("native-darken-input.procreate", incoming)
            ProcreateImport.open(incoming.inputStream(), directory).use { imported ->
                assertEquals(WIDTH, imported.document.width)
                assertEquals(HEIGHT, imported.document.height)
                val top = imported.document.layers().single { it.name == "Darken" }
                assertEquals(BlendMode.DARKEN, top.blendMode)
                assertEquals(LayerBlendContract.PROCREATE_DARKEN_19, top.blendContract)
                assertArrayEquals(sourcePixels(), imported.document.pixels(top).pixels)
                val result =
                    LayerImports.importProcreate(
                        repository,
                        imported.document,
                        preserveDocumentProfile = true,
                        rasterBudgetBytes = Long.MAX_VALUE,
                    )
                assertEquals(2, result.layers)
                assertFalse(result.flattened)
            }
            assertStack(LayerBlendContract.PROCREATE_DARKEN_19, nativePixels())
            val importedSaved = save(IMPORTED_PROJECT, "native-darken-v5-imported.artflow")
            reopen(IMPORTED_PROJECT)
            val darkenId = assertStack(LayerBlendContract.PROCREATE_DARKEN_19, nativePixels())
            assertArrayEquals(importedSaved, storage.documentFile(IMPORTED_PROJECT).readBytes())
            assertPng("native-darken-v5-native.png", nativePixels())
            assertPsd("native-darken-v5-native.psd", nativePixels(), nativeContract = true)

            // The ordinary two-argument blend picker action must change the contract even though
            // the visible enum remains DARKEN. Undo and redo must include that contract change.
            repository.setLayerBlendMode(darkenId, BlendMode.DARKEN)
            assertStack(LayerBlendContract.STANDARD, standardPixels())
            assertTrue(repository.undo())
            assertStack(LayerBlendContract.PROCREATE_DARKEN_19, nativePixels())
            assertTrue(repository.redo())
            assertStack(LayerBlendContract.STANDARD, standardPixels())
            val selectedSaved = save(IMPORTED_PROJECT, "native-darken-v5-standard-selected.artflow")
            reopen(IMPORTED_PROJECT)
            assertStack(LayerBlendContract.STANDARD, standardPixels())
            assertArrayEquals(selectedSaved, storage.documentFile(IMPORTED_PROJECT).readBytes())
            assertPng("native-darken-v5-standard.png", standardPixels())
            assertPsd("native-darken-v5-standard.psd", standardPixels(), nativeContract = false)
        }

    private suspend fun assertStack(
        contract: LayerBlendContract,
        expected: IntArray,
    ): Long {
        val layers = repository.getAllLayers()
        assertEquals(2, layers.size)
        val base = layers.single { it.name == "Base" }
        val top = layers.single { it.name == "Darken" }
        assertEquals(BlendMode.NORMAL, base.blendMode)
        assertEquals(LayerBlendContract.STANDARD, base.blendContract)
        assertEquals(BlendMode.DARKEN, top.blendMode)
        assertEquals(contract, top.blendContract)
        assertEquals(0, repository.getBackgroundColor())
        assertArrayEquals("Base raster remains editable", basePixels(), requireNotNull(repository.layerPixels(base.id)).pixels)
        assertArrayEquals("Source raster remains editable", sourcePixels(), requireNotNull(repository.layerPixels(top.id)).pixels)
        assertArrayEquals("Whole-image composite for $contract", expected, requireNotNull(repository.compositeBuffer()).pixels)
        return top.id
    }

    private suspend fun save(
        project: Long,
        name: String,
    ): ByteArray {
        assertNotNull(repository.saveCanvas(project))
        val bytes = storage.documentFile(project).readBytes()
        assertSigned(bytes, CanvasDocument.CURRENT_VERSION)
        evidence(name, bytes)
        return bytes
    }

    private suspend fun reopen(project: Long) {
        repository.dispose()
        storage = ProjectStorage(context)
        repository = CanvasRepositoryImpl(storage)
        requireNotNull(repository.loadCanvas(project))
    }

    private fun writeHistoricalRaster(
        path: String,
        pixels: IntArray,
    ) {
        val file = storage.resolve(HISTORICAL_PROJECT, path)
        requireNotNull(file.parentFile).mkdirs()
        file.writeBytes(BitmapPixelBridge.toPngBytes(PixelBuffer(WIDTH, HEIGHT, pixels)))
    }

    private suspend fun assertPng(
        name: String,
        expected: IntArray,
    ) {
        val result =
            renderedExport(
                repository,
                ArtworkExporter(context, storage),
                IMPORTED_PROJECT,
                "Native Darken",
                ExportOptions(format = ExportFormat.PNG),
            ).getOrThrow()
        val bytes = File(result.filePath).readBytes()
        evidence(name, bytes)
        val decoded = requireNotNull(BitmapPixelBridge.fromEncodedBytes(bytes))
        assertEquals(WIDTH, decoded.width)
        assertEquals(HEIGHT, decoded.height)
        assertArrayEquals("Every exported pixel", expected, decoded.pixels)
    }

    /** PSD has ordinary Darken only: verify the visible appearance and retained editable rasters separately. */
    private suspend fun assertPsd(
        name: String,
        expected: IntArray,
        nativeContract: Boolean,
    ) {
        val result =
            renderedExport(
                repository,
                ArtworkExporter(context, storage),
                IMPORTED_PROJECT,
                "Native Darken",
                ExportOptions(format = ExportFormat.PSD),
            ).getOrThrow()
        val bytes = File(result.filePath).readBytes()
        evidence(name, bytes)
        val decoded = requireNotNull(PsdCodec.read(bytes))
        assertEquals(WIDTH, decoded.width)
        assertEquals(HEIGHT, decoded.height)
        assertArrayEquals(
            "Every merged-preview pixel after PSD white-matte quantization",
            mergedPsdPixels(nativeContract),
            requireNotNull(decoded.composite).pixels,
        )
        val base = decoded.layers.single { it.name == "Base" }
        val top = decoded.layers.single { it.name == "Darken" }
        assertArrayEquals(basePixels(), base.pixels.pixels)
        assertArrayEquals(sourcePixels(), top.pixels.pixels)
        assertEquals(BlendMode.NORMAL, base.blendMode)
        assertEquals(BlendMode.DARKEN, top.blendMode)
        assertEquals(255, base.opacity)
        assertEquals(255, top.opacity)
        val visible = decoded.layers.filter { it.isVisible }
        if (nativeContract) {
            assertEquals(3, decoded.layers.size)
            assertTrue(result.warning.orEmpty().startsWith("Native Darken is rendered into Artwork"))
            assertFalse(base.isVisible)
            assertFalse(top.isVisible)
            val artwork = visible.single()
            assertEquals("Artwork (native layer blending)", artwork.name)
            assertEquals(BlendMode.NORMAL, artwork.blendMode)
            assertEquals(255, artwork.opacity)
            assertArrayEquals(expected, artwork.pixels.pixels)
        } else {
            assertEquals(2, decoded.layers.size)
            assertNull(result.warning)
            assertTrue(base.isVisible)
            assertTrue(top.isVisible)
        }
        val recomposited = PixelBuffer(WIDTH, HEIGHT)
        visible.forEach { layer -> BlendModes.composite(recomposited, layer.pixels, layer.blendMode, layer.opacity / 255f) }
        assertArrayEquals("Every pixel recomposited from the visible PSD records", expected, recomposited.pixels)
    }

    /** Explicit native field layout and exact premultiplied tiles; no reader/writer under test generates them. */
    private fun nativeFixture(): ByteArray {
        val archive = KeyedArchiveBuilder()

        fun layer(
            name: String,
            blend: Long,
        ) = archive.instance(
            "SilicaLayer",
            mapOf(
                "name" to archive.add(name),
                "UUID" to archive.add(name),
                "blend" to blend,
                "extendedBlend" to blend,
                "extendedBlend2" to blend,
            ),
        )

        val top = layer("Darken", 19L)
        val base = layer("Base", 0L)
        val root =
            mapOf(
                "\$class" to archive.classOf("SilicaDocument"),
                "size" to archive.add("{$WIDTH, $HEIGHT}"),
                "tileSize" to WIDTH.toLong(),
                "backgroundHidden" to true,
                "layers" to archive.array(listOf(top, base)),
            )
        val entries = linkedMapOf("Document.archive" to archive.encode(root))
        for ((name, pixels) in listOf("Base" to basePixels(), "Darken" to sourcePixels())) {
            val raw =
                ByteArray(pixels.size * 4) { at ->
                    val pixel = pixels[at / 4]
                    val alpha = pixel ushr 24
                    if (at % 4 == 3) {
                        alpha.toByte()
                    } else {
                        val channel = (pixel ushr intArrayOf(16, 8, 0)[at % 4]) and 255
                        ((channel * alpha + 127) / 255).toByte()
                    }
                }
            entries["$name/0~0.lz4"] =
                "bvx-".toByteArray() +
                ByteBuffer
                    .allocate(4)
                    .order(ByteOrder.LITTLE_ENDIAN)
                    .putInt(raw.size)
                    .array() + raw +
                "bvx$".toByteArray()
        }
        val output = ByteArrayOutputStream()
        ZipOutputStream(output).use { zip ->
            entries.forEach { (name, bytes) ->
                zip.putNextEntry(ZipEntry(name))
                zip.write(bytes)
                zip.closeEntry()
            }
        }
        return output.toByteArray()
    }

    private fun basePixels(): IntArray = bands(intArrayOf(0, 0xAA963CB4.toInt(), 0xFFD25A96.toInt(), 0x551ED25A))

    private fun sourcePixels(): IntArray = IntArray(WIDTH * HEIGHT) { 0x553CB45A }

    /**
     * Exact rational evaluation of min(B, S + (1 - Sa) B), including alpha, then straight-byte rounding.
     * S is premultiplied (20,60,30,85)/255. The four premultiplied B bands are zero,
     * (100,40,120,170)/255, (210,90,150,255)/255 and (10,70,30,85)/255.
     * These are mathematical fixtures from recovered dataflow, not half-float GPU execution goldens.
     */
    private fun nativePixels(): IntArray = bands(intArrayOf(0, 0xAA823CA5.toInt(), 0xFFA05A82.toInt(), 0x551ED25A))

    /** Standard source-over Darken independently rendered by the unchanged v4 baseline as well. */
    private fun standardPixels(): IntArray = bands(intArrayOf(0x553CB45A, 0xC66F4D8D.toInt(), 0xFFA05A82.toInt(), 0x8E2AC05A.toInt()))

    /**
     * PSD's merged RGB is quantized over white; editable layer planes retain their straight bytes.
     * For partial alpha a and channel c: stored = floor((c*a + 255*(255-a) + 127) / 255),
     * then restored = floor((255*(stored+a-255) + floor(a/2)) / a), clamped to 0..255.
     * These independently evaluated band literals include that round trip without calling the codec.
     * Alpha and the opaque/fully transparent bands remain unchanged.
     */
    private fun mergedPsdPixels(nativeContract: Boolean): IntArray =
        bands(
            if (nativeContract) {
                intArrayOf(0, 0xAA833CA5.toInt(), 0xFFA05A82.toInt(), 0x551ED25A)
            } else {
                intArrayOf(0x553CB45A, 0xC66F4D8C.toInt(), 0xFFA05A82.toInt(), 0x8E29C05A.toInt())
            },
        )

    private fun bands(values: IntArray): IntArray = IntArray(WIDTH * HEIGHT) { values[(it % WIDTH) / 8] }

    private fun assertSigned(
        bytes: ByteArray,
        version: Int,
    ) {
        val text = bytes.toString(Charsets.UTF_8)
        val json = JSONObject(text)
        assertEquals(version, json.getInt("version"))
        val checksum = json.getString("checksum")
        assertTrue(checksum.matches(Regex("[0-9a-f]{64}")))
        val token = "\"checksum\":\"$checksum\""
        assertEquals(1, Regex(Regex.escape(token)).findAll(text).count())
        assertEquals(checksum, sha256(text.replace(token, "\"checksum\":null").toByteArray()))
    }

    private fun evidence(
        name: String,
        bytes: ByteArray,
    ) {
        File(TestEvidence.directory(), name).writeBytes(bytes)
    }

    private fun pixelHash(pixels: IntArray): String {
        val bytes = ByteBuffer.allocate(pixels.size * Int.SIZE_BYTES)
        pixels.forEach { bytes.putInt(it) }
        return sha256(bytes.array())
    }

    private fun sha256(bytes: ByteArray): String =
        MessageDigest
            .getInstance("SHA-256")
            .digest(bytes)
            .joinToString("") { "%02x".format(it.toInt() and 255) }

    private companion object {
        const val WIDTH = 32
        const val HEIGHT = 16
        const val HISTORICAL_PROJECT = 6_250_001L
        const val IMPORTED_PROJECT = 6_250_002L
        const val HISTORICAL_SHA = "3814c6bd8a3b22dd733ecdbdbce285b8481220906264abbeb201db60715372a6"
        const val HISTORICAL_PIXELS_SHA = "d4c364947957eb1d28c19bfd7f69b4e7d63106ea8235654cac56d535f0170374"
    }
}
