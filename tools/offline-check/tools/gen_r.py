"""Generate stub R and BuildConfig sources for the harness (run as: python3 -I gen_r.py APP_DIR OUT_DIR VARIANT).

R mirrors what AGP generates with android.nonTransitiveRClass=true: only the app module's own resources.
Every resource name that exists in app/src/<sourceSet>/res becomes an `const val` Int, so a typo in
R.string.foo is reported as "Unresolved reference" exactly like in the real build.
BuildConfig carries the fields AGP generates for the variant (values read from app/build.gradle.kts).
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

KOTLIN_KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
    "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof",
    "val", "var", "when", "while",
}

# values/*.xml element -> R class
VALUE_TAGS = {
    "string": "string", "string-array": "array", "array": "array", "integer-array": "array",
    "plurals": "plurals", "color": "color", "dimen": "dimen", "bool": "bool", "integer": "integer",
    "style": "style", "attr": "attr", "fraction": "fraction", "drawable": "drawable", "id": "id",
}
# resource directory prefix -> R class
DIR_TYPES = {
    "drawable": "drawable", "mipmap": "mipmap", "xml": "xml", "raw": "raw", "font": "font", "layout": "layout",
    "anim": "anim", "animator": "animator", "menu": "menu", "navigation": "navigation", "color": "color",
    "interpolator": "interpolator", "transition": "transition",
}
ID_RE = re.compile(r"@\+id/([A-Za-z0-9_.]+)")


def ident(name):
    name = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return f"`{name}`" if name in KOTLIN_KEYWORDS else name


def collect(res_dirs):
    found = {}
    def add(kind, name):
        found.setdefault(kind, set()).add(name.replace(".", "_").replace("-", "_"))
    for res in res_dirs:
        if not os.path.isdir(res):
            continue
        for entry in sorted(os.listdir(res)):
            d = os.path.join(res, entry)
            if not os.path.isdir(d):
                continue
            base = entry.split("-")[0]
            if base == "values":
                for f in sorted(os.listdir(d)):
                    if not f.endswith(".xml"):
                        continue
                    root = ET.parse(os.path.join(d, f)).getroot()
                    for el in root:
                        tag = el.tag
                        name = el.get("name")
                        if tag == "item" and el.get("type") and name:
                            add(el.get("type"), name)
                        elif tag == "declare-styleable":
                            for a in el:
                                if a.tag == "attr" and a.get("name") and not a.get("name").startswith("android:"):
                                    add("attr", a.get("name"))
                        elif tag in VALUE_TAGS and name:
                            add(VALUE_TAGS[tag], name)
                        if tag == "style":
                            for it in el:
                                pass
            elif base in DIR_TYPES:
                for f in sorted(os.listdir(d)):
                    stem = f.split(".")[0]
                    if stem:
                        add(DIR_TYPES[base], stem)
                    if f.endswith(".xml"):
                        text = open(os.path.join(d, f), encoding="utf-8").read()
                        for m in ID_RE.finditer(text):
                            add("id", m.group(1))
    return found


def gradle_value(text, key, default):
    m = re.search(r"\b" + key + r"\s*=\s*\"([^\"]*)\"", text)
    if m:
        return m.group(1)
    m = re.search(r"\b" + key + r"\s*=\s*(\d+)", text)
    return m.group(1) if m else default


def main():
    app_dir, out_dir, variant = sys.argv[1], sys.argv[2], sys.argv[3]
    gradle = open(os.path.join(app_dir, "build.gradle.kts"), encoding="utf-8").read()
    ns = gradle_value(gradle, "namespace", "com.artflow.studio")
    res_dirs = [os.path.join(app_dir, "src", s, "res") for s in ("main", variant)]
    found = collect(res_dirs)
    lines = [f"package {ns}", "", "// Generated by tools/gen_r.py -- do not edit.", "object R {"]
    n = 0x7F010000
    for kind in sorted(found):
        lines.append(f"    object {ident(kind)} {{")
        for name in sorted(found[kind]):
            lines.append(f"        const val {ident(name)}: Int = {n}")
            n += 1
        lines.append("    }")
    lines.append("}")
    pkg_dir = os.path.join(out_dir, *ns.split("."))
    os.makedirs(pkg_dir, exist_ok=True)
    with open(os.path.join(pkg_dir, "R.kt"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    app_id = gradle_value(gradle, "applicationId", ns)
    code = gradle_value(gradle, "versionCode", "1")
    name = gradle_value(gradle, "versionName", "1.0")
    debug = "true" if variant == "debug" else "false"
    bc = f"""package {ns}

// Generated by tools/gen_r.py -- do not edit.  Mirrors the fields AGP puts into BuildConfig for the {variant} variant.
object BuildConfig {{
    @JvmField val DEBUG: Boolean = {debug}
    const val APPLICATION_ID: String = "{app_id}"
    const val BUILD_TYPE: String = "{variant}"
    const val VERSION_CODE: Int = {code}
    const val VERSION_NAME: String = "{name}"
    const val LIBRARY_PACKAGE_NAME: String = "{ns}"
}}
"""
    with open(os.path.join(pkg_dir, "BuildConfig.kt"), "w", encoding="utf-8") as fh:
        fh.write(bc)
    total = sum(len(v) for v in found.values())
    print(f"gen_r: {total} resources in {len(found)} classes -> {pkg_dir}")


main()
