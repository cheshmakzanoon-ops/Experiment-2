#!/usr/bin/env python3
"""Regenerate the pinned Unicode 17.0.0 grapheme table from local official UCD files.

Download these files beneath https://www.unicode.org/Public/17.0.0/ucd/ into one directory:
  auxiliary/GraphemeBreakProperty.txt
  auxiliary/GraphemeBreakTest.txt
  emoji/emoji-data.txt
  DerivedCoreProperties.txt
Then run: python3 tools/generate_grapheme_data.py <directory>

Inputs are hash-checked. This script does not download anything or add a runtime dependency.
The Unicode license is retained in app/src/main/resources/META-INF/UNICODE-LICENSE.txt.
"""

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT_HASHES = {
    "GraphemeBreakProperty.txt": "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89",
    "GraphemeBreakTest.txt": "e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec",
    "emoji-data.txt": "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b",
    "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
}
BREAK_PROPERTIES = {
    "CR": 1, "LF": 2, "Control": 3, "Extend": 4, "ZWJ": 5,
    "Regional_Indicator": 6, "Prepend": 7, "SpacingMark": 8,
    "L": 9, "V": 10, "T": 11, "LV": 12, "LVT": 13,
}
INDIC_PROPERTIES = {"Consonant": 0x10, "Extend": 0x20, "Linker": 0x30}


def property_rows(contents: str):
    for line in contents.splitlines():
        fields = [part.strip() for part in line.split("#", 1)[0].split(";")]
        if len(fields) < 2:
            continue
        endpoints = fields[0].split("..")
        yield int(endpoints[0], 16), int(endpoints[-1], 16), fields[1:]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    args = parser.parse_args()
    inputs = {}
    for name, digest in INPUT_HASHES.items():
        data = (args.directory / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"Unexpected Unicode 17.0.0 input: {name}")
        inputs[name] = data.decode("utf-8")

    properties = bytearray(0x110000)
    for start, end, values in property_rows(inputs["GraphemeBreakProperty.txt"]):
        if values[0] not in ("LV", "LVT"):
            properties[start:end + 1] = bytes([BREAK_PROPERTIES[values[0]]]) * (end - start + 1)
    for name, wanted in [("emoji-data.txt", "Extended_Pictographic"), ("DerivedCoreProperties.txt", "InCB")]:
        for start, end, values in property_rows(inputs[name]):
            if values[0] == wanted:
                bits = 0x40 if wanted == "Extended_Pictographic" else INDIC_PROPERTIES[values[1]]
                for point in range(start, end + 1):
                    properties[point] |= bits

    ranges = []
    for point, value in enumerate(properties):
        if value:
            if ranges and ranges[-1][1] + 1 == point and ranges[-1][2] == value:
                ranges[-1] = (ranges[-1][0], point, value)
            else:
                ranges.append((point, point, value))

    header = """// Generated by tools/generate_grapheme_data.py; do not edit the ranges by hand.
// Unicode 17.0.0 data: Copyright © 2025 Unicode, Inc. Unicode License V3.
// Full notice: app/src/main/resources/META-INF/UNICODE-LICENSE.txt.
// Sources and SHA-256 checksums are pinned in the generator.
package com.artflow.studio.core.text

/**
 * Sorted, disjoint ranges encoded as 0xFIRST_LAST_PROPERTIES (24, 24 and 8 bits).
 * Property bits 0..3: Grapheme_Cluster_Break; bits 4..5: Indic_Conjunct_Break; bit 6: Extended_Pictographic.
 * Unlisted code points have all default values. Hangul LV/LVT is calculated below.
 */
internal object GraphemeData {
    const val BREAK_MASK = 0x0F
    const val OTHER = 0
    const val CR = 1
    const val LF = 2
    const val CONTROL = 3
    const val EXTEND = 4
    const val ZWJ = 5
    const val REGIONAL_INDICATOR = 6
    const val PREPEND = 7
    const val SPACING_MARK = 8
    const val L = 9
    const val V = 10
    const val T = 11
    const val LV = 12
    const val LVT = 13
    const val INDIC_MASK = 0x30
    const val CONSONANT = 0x10
    const val INDIC_EXTEND = 0x20
    const val LINKER = 0x30
    const val PICTOGRAPHIC = 0x40

    fun properties(codePoint: Int): Int {
        if (codePoint in 0xAC00..0xD7A3) return if ((codePoint - 0xAC00) % 28 == 0) LV else LVT
        var low = 0
        var high = ranges.lastIndex
        while (low <= high) {
            val middle = (low + high) ushr 1
            val range = ranges[middle]
            when {
                codePoint < (range ushr 32).toInt() -> high = middle - 1
                codePoint > (range ushr 8 and 0xFFFFFF).toInt() -> low = middle + 1
                else -> return range.toInt() and 0xFF
            }
        }
        return OTHER
    }

    private val ranges =
        longArrayOf(
"""
    rows = "".join(f"            0x{start:06X}_{end:06X}_{value:02X}L,\n" for start, end, value in ranges)
    output = ROOT / "app/src/main/java/com/artflow/studio/core/text/GraphemeData.kt"
    output.write_text(header + rows + "        )\n}\n", encoding="utf-8")
    fixture = ROOT / "app/src/test/resources/unicode/GraphemeBreakTest-17.0.0.txt"
    fixture.parent.mkdir(parents=True, exist_ok=True)
    fixture.write_bytes((args.directory / "GraphemeBreakTest.txt").read_bytes())
    print(f"{len(ranges)} ranges; {len(ranges) * 8} bytes of Long payload; {output.stat().st_size} source bytes")


if __name__ == "__main__":
    main()
